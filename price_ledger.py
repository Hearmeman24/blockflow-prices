"""The price ledger: a schema-versioned JSON list of provider prices.

``prices.json`` is regenerated by ``update_price_ledger.py`` from the
providers' public price lists (a daily GitHub Action runs it). Every loader
goes through :func:`validate_ledger`; the BlockFlow app keeps an identical
copy of this module to check the file it downloads.

Format (``schema_version`` 1)::

    {
      "schema_version": 1,
      "generated_at": "2026-11-15T10:00:00Z",
      "sources": {
        "<source key>": {"url": "https://...", "fetched_at": "<ISO 8601>",
                         "local_copy"?: "<repo path>", "note"?: "..."}
      },
      "entries": [
        {"provider": "kie" | "piapi",
         "model": "<provider model identifier>",   # Kie model string; PiAPI task_type or kling:<version>
         "resolution": "720p" | "1k" | ... | null, # lower case
         "variant": "video_input" | null,          # other billing dimensions
         "unit": "<one of UNITS>",                 # credits_* for Kie, usd_* for PiAPI
         "amount": <positive number>,
         "usd"?: <number>,                         # USD equivalent, when the source lists it
         "source": "<source key>",
         "source_row": "<the provider's row text>"}
      ]
    }

An entry's date (``as_of``) is its source's ``fetched_at`` date.

Optional ``not_priceable``: models a provider lists but that cannot be priced
up front, copied from ``model-map.json`` by the updater::

    {"provider": "kie", "model": "gpt-image-2-6/flare-text-to-image",
     "variant"?: "video_input", "code": "<one of NOTE_CODES>",
     "message": "Kie prices this model per token, ...", "source": "https://..."}
"""

from __future__ import annotations

import json
import math
import re
from collections.abc import Mapping
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any

SCHEMA_VERSION = 1
ROOT = Path(__file__).resolve().parent
BUNDLED_PATH = ROOT / "prices.json"
MODEL_MAP_PATH = ROOT / "model-map.json"

PROVIDER_UNITS: dict[str, frozenset[str]] = {
    "kie": frozenset({"credits_per_second", "credits_per_image", "credits_per_extra_image",
                      "credits_per_reference_image"}),
    "piapi": frozenset({"usd_per_second", "usd_per_image", "usd_per_extra_image", "usd_per_megapixel"}),
}
UNITS = frozenset().union(*PROVIDER_UNITS.values())
MAX_AMOUNT = 100_000.0
NOTE_CODES = frozenset({"priced_per_token", "input_video_billing_unknown", "conflicting_sources",
                        "no_published_price"})
_NOTE_FIELDS = {"provider", "model", "variant", "code", "message", "source"}
MAX_ENTRIES = 5_000

_KEY_RE = re.compile(r"^[a-z0-9_]{1,64}$")
_RES_RE = re.compile(r"^[0-9a-z.]{1,16}$")
_VARIANT_RE = re.compile(r"^[a-z0-9_]{1,32}$")
_ENTRY_FIELDS = {"provider", "model", "resolution", "variant", "unit", "amount", "usd", "source", "source_row"}
_SOURCE_FIELDS = {"url", "fetched_at", "local_copy", "note"}


class LedgerError(ValueError):
    """The ledger (or model map) is not valid. The message says where."""


@dataclass(frozen=True)
class Entry:
    provider: str
    model: str
    unit: str
    amount: float
    source: str
    source_row: str
    as_of: str
    resolution: str | None = None
    variant: str | None = None
    usd: float | None = None

    @property
    def key(self) -> tuple[str, str, str, str | None, str | None]:
        return (self.provider, self.model, self.unit, self.resolution, self.variant)

    def as_json(self) -> dict[str, Any]:
        out: dict[str, Any] = {"provider": self.provider, "model": self.model, "resolution": self.resolution,
                               "variant": self.variant, "unit": self.unit, "amount": self.amount}
        if self.usd is not None:
            out["usd"] = self.usd
        out.update(source=self.source, source_row=self.source_row)
        return out


@dataclass(frozen=True)
class Note:
    """A model the provider lists but that cannot be priced up front, and why."""

    provider: str
    model: str
    code: str
    message: str
    source: str
    variant: str | None = None

    def as_json(self) -> dict[str, Any]:
        out: dict[str, Any] = {"provider": self.provider, "model": self.model}
        if self.variant is not None:
            out["variant"] = self.variant
        out.update(code=self.code, message=self.message, source=self.source)
        return out


@dataclass(frozen=True)
class Ledger:
    schema_version: int
    generated_at: str
    sources: Mapping[str, Mapping[str, str]]
    entries: tuple[Entry, ...]
    notes: tuple[Note, ...] = ()
    _index: dict = field(default_factory=dict, repr=False, compare=False)

    def note(self, provider: str, model: str, variant: str | None = None) -> Note | None:
        """The note for this model and variant, else one for the model as a whole."""
        for wanted in (variant, None):
            for n in self.notes:
                if (n.provider, n.model, n.variant) == (provider, model, wanted):
                    return n
        return None

    def find(self, provider: str, model: str, unit: str, resolution: str | None = None,
             variant: str | None = None) -> Entry | None:
        if not self._index:
            self._index.update({e.key: e for e in self.entries})
        return self._index.get((provider, model, unit, resolution, variant))

    @property
    def generated_date(self) -> str:
        return self.generated_at[:10]


def _iso(value: Any, where: str) -> str:
    if not isinstance(value, str):
        raise LedgerError(f"{where} must be an ISO 8601 date-time string")
    try:
        datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        raise LedgerError(f"{where} is not an ISO 8601 date-time: {value[:40]!r}") from None
    return value


def _number(value: Any, where: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(float(value)):
        raise LedgerError(f"{where} must be a finite number")
    value = float(value)
    if not 0 < value <= MAX_AMOUNT:
        raise LedgerError(f"{where} must be > 0 and <= {MAX_AMOUNT:g}")
    return value


def _text(value: Any, where: str, limit: int = 300) -> str:
    if not isinstance(value, str) or not value.strip() or len(value) > limit:
        raise LedgerError(f"{where} must be a non-empty string of at most {limit} characters")
    return value


def _sources(raw: Any) -> dict[str, dict[str, str]]:
    if not isinstance(raw, Mapping) or not raw:
        raise LedgerError("sources must be a non-empty object")
    out: dict[str, dict[str, str]] = {}
    for key, src in raw.items():
        where = f"sources.{key}"
        if not isinstance(key, str) or not _KEY_RE.match(key):
            raise LedgerError(f"{where}: source keys are lower-case letters, digits and _")
        if not isinstance(src, Mapping):
            raise LedgerError(f"{where} must be an object")
        extra = set(src) - _SOURCE_FIELDS
        if extra:
            raise LedgerError(f"{where} has unknown field(s): {', '.join(sorted(extra))}")
        url = _text(src.get("url"), f"{where}.url", 500)
        if not url.startswith("https://"):
            raise LedgerError(f"{where}.url must be an https:// URL")
        clean = {"url": url, "fetched_at": _iso(src.get("fetched_at"), f"{where}.fetched_at")}
        for opt in ("local_copy", "note"):
            if opt in src:
                clean[opt] = _text(src[opt], f"{where}.{opt}", 500)
        out[key] = clean
    return out


def _entry(raw: Any, i: int, sources: Mapping[str, Mapping[str, str]]) -> Entry:
    where = f"entries[{i}]"
    if not isinstance(raw, Mapping):
        raise LedgerError(f"{where} must be an object")
    extra = set(raw) - _ENTRY_FIELDS
    if extra:
        raise LedgerError(f"{where} has unknown field(s): {', '.join(sorted(extra))}")
    provider = raw.get("provider")
    if provider not in PROVIDER_UNITS:
        raise LedgerError(f"{where}.provider must be one of {', '.join(sorted(PROVIDER_UNITS))}")
    unit = raw.get("unit")
    if unit not in UNITS:
        raise LedgerError(f"{where}.unit must be one of {', '.join(sorted(UNITS))}")
    if unit not in PROVIDER_UNITS[provider]:
        raise LedgerError(f"{where}.unit {unit} is not a {provider} unit")
    model = _text(raw.get("model"), f"{where}.model", 120).strip()
    resolution, variant = raw.get("resolution"), raw.get("variant")
    if resolution is not None and (not isinstance(resolution, str) or not _RES_RE.match(resolution)):
        raise LedgerError(f"{where}.resolution must be null or lower-case like 720p / 1k")
    if variant is not None and (not isinstance(variant, str) or not _VARIANT_RE.match(variant)):
        raise LedgerError(f"{where}.variant must be null or lower-case letters, digits and _")
    usd = raw.get("usd")
    usd = None if usd is None else _number(usd, f"{where}.usd")
    source = raw.get("source")
    if source not in sources:
        raise LedgerError(f"{where}.source {str(source)[:40]!r} is not listed in sources")
    return Entry(provider=provider, model=model, unit=unit, amount=_number(raw.get("amount"), f"{where}.amount"),
                 source=source, source_row=_text(raw.get("source_row"), f"{where}.source_row"),
                 as_of=sources[source]["fetched_at"][:10], resolution=resolution, variant=variant, usd=usd)


def validate_ledger(data: Any) -> Ledger:
    """A validated, immutable :class:`Ledger`, or :class:`LedgerError`. Never mutates ``data``."""
    if not isinstance(data, Mapping):
        raise LedgerError("the ledger must be a JSON object")
    version = data.get("schema_version")
    if isinstance(version, bool) or version != SCHEMA_VERSION:
        raise LedgerError(f"schema_version must be {SCHEMA_VERSION}")
    generated_at = _iso(data.get("generated_at"), "generated_at")
    sources = _sources(data.get("sources"))
    raw_entries = data.get("entries")
    if not isinstance(raw_entries, list) or not raw_entries:
        raise LedgerError("entries must be a non-empty list")
    if len(raw_entries) > MAX_ENTRIES:
        raise LedgerError(f"entries has more than {MAX_ENTRIES} items")
    entries = [_entry(raw, i, sources) for i, raw in enumerate(raw_entries)]
    seen: set = set()
    for e in entries:
        if e.key in seen:
            raise LedgerError(f"duplicate entry for {e.provider} {e.model} {e.unit} {e.resolution} {e.variant}")
        seen.add(e.key)
    raw_notes = data.get("not_priceable", [])
    if not isinstance(raw_notes, list):
        raise LedgerError("not_priceable must be a list")
    notes = tuple(validate_note(n, f"not_priceable[{i}]") for i, n in enumerate(raw_notes))
    return Ledger(SCHEMA_VERSION, generated_at, sources, tuple(entries), notes)


def validate_note(raw: Any, where: str) -> Note:
    if not isinstance(raw, Mapping):
        raise LedgerError(f"{where} must be an object")
    extra = set(raw) - _NOTE_FIELDS
    if extra:
        raise LedgerError(f"{where} has unknown field(s): {', '.join(sorted(extra))}")
    if raw.get("provider") not in PROVIDER_UNITS:
        raise LedgerError(f"{where}.provider must be one of {', '.join(sorted(PROVIDER_UNITS))}")
    if raw.get("code") not in NOTE_CODES:
        raise LedgerError(f"{where}.code must be one of {', '.join(sorted(NOTE_CODES))}")
    variant = raw.get("variant")
    if variant is not None and (not isinstance(variant, str) or not _VARIANT_RE.match(variant)):
        raise LedgerError(f"{where}.variant must be null or lower-case letters, digits and _")
    source = _text(raw.get("source"), f"{where}.source", 500)
    if not all(part.strip().startswith("https://") for part in source.split(";")):
        raise LedgerError(f"{where}.source must be https:// URL(s) separated by ';'")
    return Note(provider=raw["provider"], model=_text(raw.get("model"), f"{where}.model", 120).strip(),
                code=raw["code"], message=_text(raw.get("message"), f"{where}.message", 300), source=source,
                variant=variant)


def load_file(path: Path) -> Ledger:
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise LedgerError(f"could not read {Path(path).name}: {type(exc).__name__}") from None
    return validate_ledger(data)


def load_bundled() -> Ledger:
    return load_file(BUNDLED_PATH)


def ledger_json(ledger: Ledger) -> dict[str, Any]:
    out = {"schema_version": ledger.schema_version, "generated_at": ledger.generated_at,
           "sources": {k: dict(v) for k, v in ledger.sources.items()},
           "entries": [e.as_json() for e in ledger.entries]}
    if ledger.notes:
        out["not_priceable"] = [n.as_json() for n in ledger.notes]
    return out


def dumps(data: Mapping[str, Any]) -> str:
    """Stable, diff-friendly JSON text."""
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


# ------------------------------------------------------------------ model map


def _target(raw: Any, where: str, provider: str) -> dict[str, Any]:
    if not isinstance(raw, Mapping) or set(raw) - {"model", "resolution", "variant", "unit"}:
        raise LedgerError(f"{where} must be an object with model, resolution?, variant?, unit?")
    _text(raw.get("model"), f"{where}.model", 120)
    res, var = raw.get("resolution"), raw.get("variant")
    if res is not None and (not isinstance(res, str) or not _RES_RE.match(res)):
        raise LedgerError(f"{where}.resolution is invalid")
    if var is not None and (not isinstance(var, str) or not _VARIANT_RE.match(var)):
        raise LedgerError(f"{where}.variant is invalid")
    if "unit" in raw and raw["unit"] not in PROVIDER_UNITS[provider]:
        raise LedgerError(f"{where}.unit is not a {provider} unit")
    return dict(raw)


def validate_model_map(data: Any) -> dict[str, Any]:
    """Checks ``model-map.json`` (see that file's ``_doc``). Returns it unchanged."""
    if not isinstance(data, Mapping) or data.get("schema_version") != SCHEMA_VERSION:
        raise LedgerError(f"model map: schema_version must be {SCHEMA_VERSION}")
    kie = data.get("kie")
    if not isinstance(kie, Mapping) or not isinstance(kie.get("rows"), list) or not kie["rows"]:
        raise LedgerError("model map: kie.rows must be a non-empty list")
    seen: set[str] = set()
    for i, row in enumerate(kie["rows"]):
        where = f"model map: kie.rows[{i}]"
        if not isinstance(row, Mapping):
            raise LedgerError(f"{where} must be an object")
        desc = _text(row.get("description"), f"{where}.description").strip().lower()
        if desc in seen:
            raise LedgerError(f"{where}: duplicate description")
        seen.add(desc)
        if row.get("unit") not in PROVIDER_UNITS["kie"]:
            raise LedgerError(f"{where}.unit must be a kie unit")
        targets = row.get("targets")
        if not isinstance(targets, list) or not targets:
            raise LedgerError(f"{where}.targets must be a non-empty list")
        for j, t in enumerate(targets):
            _target(t, f"{where}.targets[{j}]", "kie")
    for i, note in enumerate(data.get("not_priceable", [])):
        validate_note(note, f"model map: not_priceable[{i}]")
    piapi = data.get("piapi")
    if not isinstance(piapi, Mapping) or not isinstance(piapi.get("docs"), list) or not piapi["docs"]:
        raise LedgerError("model map: piapi.docs must be a non-empty list")
    for i, doc in enumerate(piapi["docs"]):
        where = f"model map: piapi.docs[{i}]"
        if not isinstance(doc, Mapping):
            raise LedgerError(f"{where} must be an object")
        if not isinstance(doc.get("source"), str) or not _KEY_RE.match(doc["source"]):
            raise LedgerError(f"{where}.source must be a source key")
        _text(doc.get("path"), f"{where}.path", 200)
        for j, table in enumerate(doc.get("tables") or []):
            tw = f"{where}.tables[{j}]"
            if not isinstance(table, Mapping) or table.get("unit") not in PROVIDER_UNITS["piapi"]:
                raise LedgerError(f"{tw}.unit must be a piapi unit")
            _text(table.get("after"), f"{tw}.after")
            for name in ("rows", "columns"):
                if not isinstance(table.get(name), Mapping) or not table[name]:
                    raise LedgerError(f"{tw}.{name} must be a non-empty object")
        for j, pat in enumerate(doc.get("patterns") or []):
            pw = f"{where}.patterns[{j}]"
            if not isinstance(pat, Mapping):
                raise LedgerError(f"{pw} must be an object")
            try:
                if re.compile(_text(pat.get("regex"), f"{pw}.regex")).groups != 1:
                    raise LedgerError(f"{pw}.regex must have exactly one group (the price)")
            except re.error:
                raise LedgerError(f"{pw}.regex is not a valid regular expression") from None
            if pat.get("unit") not in PROVIDER_UNITS["piapi"] or not isinstance(pat.get("targets"), list):
                raise LedgerError(f"{pw} needs a piapi unit and a targets list")
            for k, t in enumerate(pat["targets"]):
                _target(t, f"{pw}.targets[{k}]", "piapi")
    return dict(data)
